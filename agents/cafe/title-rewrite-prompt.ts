export interface TitleRewritePromptInput {
  title: string
  body: string
  boardName?: string | null
  commentCount?: number
  likeCount?: number
  desireCategory?: string | null
  emotionTags?: readonly string[]
  psychInsight?: string | null
  /** gate가 통과시키며 남긴 보호 신호 — 왜 좋은 글인지 모델에게 알려준다 */
  gateSignals?: readonly string[]
}

/** 본문이 지나치게 길면 앞부분만 넘긴다 — 제목 근거는 대개 도입부에 있다 */
const MAX_BODY_CHARS = 1800

export function buildTitleRewritePrompt(input: TitleRewritePromptInput): string {
  const body = input.body.replace(/\s+/g, ' ').trim().slice(0, MAX_BODY_CHARS)
  return `[원제목] ${input.title}   (${input.title.length}자)

[본문] (${body.length}자)
${body}

[반응] 댓글 ${input.commentCount ?? 0} · 공감 ${input.likeCount ?? 0}
[게시판] ${input.boardName ?? '-'}
[분석] 욕망=${input.desireCategory ?? '-'} · 감정=${(input.emotionTags ?? []).join(', ') || '-'}
[심리] ${input.psychInsight ?? '-'}
[후보 신호] ${(input.gateSignals ?? []).join(' · ') || '-'}

위 본문에 실제로 있는 것만 써라. JSON 하나만 출력하라.`
}
