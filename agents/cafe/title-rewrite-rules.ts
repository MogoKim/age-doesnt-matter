/** 화자 본인이 20~30대라고 말하는 경우 — 1인칭 자기지시와 결합될 때만 */
export const YOUNG_SELF_AGE_PATTERN =
  /(저|제가|나는|내가)[는가]?[^.。\n]{0,10}(20대|30대|스물|서른)|제 ?나이[가는]?[^.。\n]{0,8}(20대|30대|2[0-9]살|3[0-9]살)|올해 ?(스물|서른)/

/** 20~30대 생애 사건 — 화자 본인 현재형일 때만 (과거 회상이면 무효) */
