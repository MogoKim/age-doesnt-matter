/** 임신·출산 — 며느리·딸 이야기가 압도적이라 1인칭 결합을 요구한다 */
export const PREGNANCY_PATTERN = /임신 ?중|임신했|출산 ?준비|만삭/
export const PREGNANCY_FIRST_PERSON = /(제가|저는|내가|나는)[^.。\n]{0,10}(임신|출산)|임신 ?했어요|제 ?출산/

/**
 * 연애 — ★ 소유격이 있을 때만 화자 본인 것으로 본다.
 * "딸이 사귀는 남친", "언니가 소개팅을 해줬어요"는 화자 본인의 연애가 아니다.
 * "제가 남자친구라면"은 가정법이라 소유격이 아니므로 걸리지 않는다.
 */
export const YOUNG_ROMANCE_OWN_PATTERN = /(제|내|저의|나의) ?(남친|남자친구|여친)|제 ?소개팅|소개팅[^.。\n]{0,8}(나갔|받았|해봤)/

/** 과거 회상 표지 — 있으면 20~30대 신호를 무효화한다 */
