export type RewriteGateReason =
  | 'NOT_TARGET_SOURCE'
  | 'SHADOW_SOURCE'
  | 'BODY_TOO_SHORT'
  | 'NOT_USABLE'
  | 'AD_OR_EVENT'
  | 'MEDICAL_AD'
  | 'NEWS_SCRAP'
  | 'PARENTING_CURRENT'
  | 'YOUNG_SELF'
  | 'MALE_SELF'

export interface RewriteGateResult {
  /** true면 Sonnet 호출 대상 */
  eligible: boolean
  /** 제외 사유 (eligible=true면 null) */
  reason: RewriteGateReason | null
  /** 사람이 읽을 근거 한 줄 */
  detail: string
  /** 통과 시 감지된 보호 신호 — 검수 시 참고용 */
  signals: string[]
}
