const fix = (s: string): string => GUIDE_TEXT_OVERRIDES.reduce((acc, [from, to]) => acc.split(from).join(to), s)

/** 가이드의 모든 표시 문자열(제목·설명·요약·섹션·FAQ·링크 라벨)에 보정 적용 */
export function applyGuideOverrides(g: GuideDoc): GuideDoc {
  return {
    ...g,
    title: fix(g.title),
    description: fix(g.description),
    breadcrumbLabel: fix(g.breadcrumbLabel),
    tldr: fix(g.tldr),
    sections: g.sections.map((s) => ({ heading: fix(s.heading), paragraphs: s.paragraphs.map(fix) })),
    faqs: g.faqs.map((f) => ({ q: fix(f.q), a: fix(f.a) })),
    communityLinks: [],
    relatedLinks: g.relatedLinks.map((l) => ({ label: fix(l.label), href: l.href })),
  }
}
